/** Our shape id for any shape name Mermaid accepts. Unknown names pass through unchanged. */
export function canonicalShape(type: string | undefined): string {
  if (!type) {
    return 'rect';
  }
  if (SHAPE_BY_ID.has(type)) {
    return type;
  }
  return ALIASES.get(type) ?? type;
}
